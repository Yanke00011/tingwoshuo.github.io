// Use a local Playwright installation: node scripts/sync-brand.mjs /absolute/path/to/playwright/index.mjs
import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const blog = new URL('../', import.meta.url);
const studio = new URL('../tingwoshuo-Studio/', blog);
const markPath = new URL('public/brand/mark.svg', blog);
const mark = await readFile(markPath, 'utf8');
const symbol = mark.slice(mark.indexOf('>') + 1, mark.lastIndexOf('</svg>'));
const svg = (width, height, content) => `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">${content}</svg>\n`;
const wordmark = (ink, secondary) => svg(280, 72, `<g transform="translate(4 4)">${symbol}</g><g font-family="PingFang SC, Microsoft YaHei, system-ui, sans-serif"><text x="84" y="35" fill="${ink}" font-size="27" font-weight="650">听我说</text><text x="85" y="56" fill="${secondary}" font-size="12" letter-spacing="2">HEAR ME OUT</text></g>`);
await writeFile(new URL('public/brand/wordmark.svg', blog), wordmark('#241932', '#655972'));
await writeFile(new URL('public/brand/wordmark-dark.svg', blog), wordmark('#fff8f3', '#d0c2dc'));
await copyFile(markPath, new URL('public/favicon.svg', blog));
await mkdir(new URL('public/brand/', studio), { recursive: true });
await copyFile(markPath, new URL('public/brand/mark.svg', studio));
const css = await readFile(new URL('src/styles/global.css', blog), 'utf8');
const roles = ['bg','surface','surface-soft','text','secondary','muted','line','line-strong','accent','accent-strong','accent-wash','on-accent','ink','ink-text','signal','life-wash','life-ink','cover-ratio','radius-control','radius-panel','duration','ease'];
function pick(block) {
  return roles.map((role) => block.match(new RegExp(`^  --${role}: .+;$`, 'm'))?.[0]).filter(Boolean).join('\n');
}
const light = css.match(/:root \{([^}]+)}/)?.[1] ?? '';
const dark = css.match(/:root\[data-theme="dark"\] \{([^}]+)}/)?.[1] ?? '';
await writeFile(new URL('src/ui/brand-tokens.css', studio), `/* Generated by blog/scripts/sync-brand.mjs */\n:root {\n${pick(light)}\n}\n@media (prefers-color-scheme: dark) {\n:root {\n${pick(dark)}\n}\n}\n`);

if (process.argv[2]) {
  const { chromium } = await import(pathToFileURL(process.argv[2]).href);
  const browser = await chromium.launch({ channel: 'chrome' });
  async function raster(content, width, height, url) {
    const page = await browser.newPage({ viewport: { width, height } });
    await page.setContent('<style>body{margin:0}svg{display:block}</style>' + content);
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: decodeURIComponent(url.pathname) });
    await page.close();
  }
  try {
    const icon = (size) => svg(size, size, `<rect width="${size}" height="${size}" fill="#241932"/><g transform="scale(${size / 64})">${symbol}</g>`);
    await raster(icon(180), 180, 180, new URL('public/apple-touch-icon.png', blog));
    await raster(icon(512), 512, 512, new URL('public/brand/app-icon.png', studio));
    const og = svg(1200, 630, `<rect width="1200" height="630" fill="#241932"/><path d="M80 82H1120M80 548H1120" stroke="#796687"/><g transform="translate(825 161) scale(4.25)">${symbol}</g><g font-family="PingFang SC, Microsoft YaHei, system-ui, sans-serif"><text x="82" y="329" font-size="102" font-weight="650" fill="#fff8f3">听我说<tspan fill="#ffae92">。</tspan></text><text x="88" y="405" font-size="29" letter-spacing="5" fill="#e3d3ed">HEAR ME OUT</text></g>`);
    await writeFile(new URL('public/og.svg', blog), og);
    await raster(og, 1200, 630, new URL('public/og.png', blog));
  } finally { await browser.close(); }
}
